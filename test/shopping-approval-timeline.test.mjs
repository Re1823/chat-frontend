import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';
import { createPurchaseStore } from '../src/shopping/purchases.mjs';
import { createShoppingApprovalApi } from '../src/shopping/approval-api.mjs';
import { createDwellServer } from '../server.mjs';

test('approval timeline insertion, in-place states, replay, dedup and mobile keyboard layout',async()=>{
  const ownerId='owner@example.com';
  const path=join(await mkdtemp(join(tmpdir(),'shopping-card-')),'purchases.json');
  const store=createPurchaseStore({path,approvalSecret:'phase3-ui-test-secret-with-32-plus-chars'});await store.load();
  const order={platform:'taobao',merchant:'得力办公文具',goods:'得力中性笔',sku:'红色1支+笔芯2支',skuId:'6261131742582',quantity:1,subtotalMinor:480,shippingMinor:0,discountMinor:62,totalMinor:418,addressLabel:'四川省 成都市 · ****8076',resourceUrl:'https://item.taobao.com/item.htm?id=671224654225',confirmationPage:'https://buy.taobao.com/auction/buy_now.jhtml',category:'physical_goods'};
  const create=async()=>{const session=await store.startSession({ownerId,conversationId:'claude-main',workerId:'windows-1',browserContextId:'edge-1',profileId:'shopping',pageUrl:order.resourceUrl});return store.create({ownerId,conversationId:'claude-main',sessionId:session.sessionId,workerOrder:order})};
  const approve=await create(),reject=await create(),expired=await create();
  await store.transition({purchaseId:expired.purchaseId,expectedState:'pending_approval',nextState:'expired'});
  const shoppingApprovalApi=createShoppingApprovalApi({purchaseStore:store,verifyOwner:async req=>req.headers['x-test-owner']===ownerId?ownerId:null});
  const server=createDwellServer({shoppingApprovalApi});await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const context=await browser.newContext({extraHTTPHeaders:{'x-test-owner':ownerId}});
    const page=await context.newPage();
    await page.addInitScript((timestamp)=>{localStorage.setItem('dwell.provider','claude_tmux');localStorage.setItem('dwell.active','timeline-test');localStorage.setItem('dwell.sessions',JSON.stringify([{id:'timeline-test',provider:'claude_tmux',title:'Timeline',messages:[{role:'user',content:'before card',createdAt:timestamp-1000},{role:'assistant',content:'after card',createdAt:timestamp+1000}]}]));},approve.createdAt);
    await page.goto(`http://127.0.0.1:${server.address().port}/`);
    await page.locator('.shopping-approval-card').first().waitFor();
    assert.equal(await page.locator('.shopping-approval-card').count(),3);
    const pendingCard=page.locator(`[data-shopping-purchase="${approve.purchaseId}"]`),expiredCard=page.locator(`[data-shopping-purchase="${expired.purchaseId}"]`);
    assert.equal(await pendingCard.locator('h2').isVisible(),true);
    assert.equal(await pendingCard.evaluate(n=>n.parentElement.id),'messages');
    assert.equal(await page.locator('#shoppingApprovals,.shopping-approvals').count(),0);
    assert.equal(await pendingCard.evaluate(n=>{const s=getComputedStyle(n);return s.position==='static'&&s.bottom==='auto'&&s.transform==='none'}),true);
    await page.evaluate(()=>{const host=document.querySelector('#messages');host.style.scrollBehavior='auto';for(let i=0;i<15;i++){const n=document.createElement('div');n.textContent='later fixture message';n.style.height='100px';host.append(n)}host.scrollTop=0});
    const beforeScroll=await pendingCard.boundingBox();
    await page.evaluate(()=>document.querySelector('#messages').scrollTop=600);
    const afterScroll=await pendingCard.boundingBox();
    assert.ok(Math.abs((beforeScroll.y-afterScroll.y)-600)<2,'card moves with message scrolling');
    await page.evaluate(()=>{const host=document.querySelector('#messages');while(host.lastElementChild?.textContent==='later fixture message')host.lastElementChild.remove();host.scrollTop=0});

    assert.equal(await page.evaluate(id=>{const card=document.querySelector('[data-shopping-purchase="'+id+'"]'),before=document.querySelector('[data-message-index="0"]'),after=document.querySelector('[data-message-index="1"]');return !!(before.compareDocumentPosition(card)&Node.DOCUMENT_POSITION_FOLLOWING)&&!!(card.compareDocumentPosition(after)&Node.DOCUMENT_POSITION_FOLLOWING)},approve.purchaseId),true);
    await page.evaluate(()=>loadShoppingApprovals());assert.equal(await pendingCard.count(),1);
    await pendingCard.evaluate(n=>{window.testCardIdentity=n});
    assert.equal(await expiredCard.locator('h2').count(),0);
    assert.match(await expiredCard.innerText(),/秋秋选好了 · ¥4\.18.*审批已过期/s);
    const compactHeight=(await expiredCard.boundingBox()).height;
    assert.ok(compactHeight<80,`expired card too tall: ${compactHeight}`);
    await expiredCard.locator('[data-shopping-toggle]').click();
    assert.equal(await expiredCard.locator('h2').isVisible(),true);
    await page.evaluate(()=>renderShoppingApprovalCards());
    assert.equal(await expiredCard.locator('h2').isVisible(),true);
    await expiredCard.locator('[data-shopping-toggle]').click();
    assert.equal(await expiredCard.locator('h2').count(),0);
    assert.equal(await page.locator('#messages').isVisible(),true);
    assert.match(await page.locator('#messages').innerText(),/¥4\.18/);
    assert.doesNotMatch(await page.locator('#messages').innerText(),/6261131742582|fingerprint|nonce/);
    if(process.env.QIUQIU_SHOPPING_CARD_SCREENSHOT)await page.screenshot({path:process.env.QIUQIU_SHOPPING_CARD_SCREENSHOT});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await page.locator(`[data-shopping-purchase="${approve.purchaseId}"] [data-shopping-decision="approve"]`).isVisible(),true);
    await page.setViewportSize({width:390,height:420});await page.locator('#input').focus();
    await page.waitForFunction(()=>!keyboardViewportPending);
    await page.evaluate(()=>{const host=document.querySelector('#messages');host.style.scrollBehavior='auto';host.scrollTop=host.scrollHeight});
    await page.waitForFunction(()=>{const h=document.querySelector('#messages');h.scrollTop=h.scrollHeight;return document.querySelector('[data-message-index="1"]').getBoundingClientRect().bottom<=document.querySelector('#input').getBoundingClientRect().top},{},{timeout:2000});
    const layout=await page.evaluate(()=>({width:document.documentElement.scrollWidth,screen:innerWidth,input:document.querySelector('#input').getBoundingClientRect().top,latest:document.querySelector('[data-message-index="1"]').getBoundingClientRect().bottom,cardPosition:getComputedStyle(document.querySelector('.shopping-approval-card')).position}));assert.ok(layout.width<=layout.screen);assert.ok(layout.latest<=layout.input);assert.equal(layout.cardPosition,'static');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await pendingCard.evaluate(n=>n.parentElement.id),'messages');
    assert.equal(await pendingCard.evaluate(n=>getComputedStyle(n).position),'static');
    await page.reload();
    await page.locator('.shopping-approval-card').first().waitFor();
    assert.equal(await page.locator('.shopping-approval-card').count(),3);
    assert.equal(await page.locator(`[data-shopping-purchase="${expired.purchaseId}"] h2`).count(),0);
    assert.equal(await page.locator('#input').isVisible(),true);
    assert.equal(await page.locator('#messages').isVisible(),true);
    await pendingCard.evaluate(n=>{window.testCardIdentity=n});
    await page.locator(`[data-shopping-purchase="${approve.purchaseId}"] [data-shopping-decision="approve"]`).click();
    await page.locator(`[data-shopping-purchase="${approve.purchaseId}"]`).getByText('已批准').waitFor();
    assert.equal(await page.evaluate(id=>document.querySelector('[data-shopping-purchase="'+id+'"]')===window.testCardIdentity,approve.purchaseId),true);
    await page.locator('[data-shopping-purchase="'+reject.purchaseId+'"]').evaluate(n=>window.testExpireIdentity=n);
    await store.transition({purchaseId:reject.purchaseId,expectedState:'pending_approval',nextState:'expired'});
    await page.evaluate(()=>loadShoppingApprovals());
    assert.equal(await page.evaluate(id=>document.querySelector('[data-shopping-purchase="'+id+'"]')===window.testExpireIdentity,reject.purchaseId),true);
    await page.reload();
    await page.locator(`[data-shopping-purchase="${approve.purchaseId}"]`).getByText('已批准').waitFor();
    await page.locator(`[data-shopping-purchase="${reject.purchaseId}"]`).getByText('审批已过期').waitFor();
    for(const id of [approve.purchaseId,reject.purchaseId,expired.purchaseId])assert.equal(await page.locator(`[data-shopping-purchase="${id}"] h2`).count(),0);
    assert.equal(store.get({ownerId,purchaseId:approve.purchaseId}).state,'approved');
    assert.equal(store.get({ownerId,purchaseId:reject.purchaseId}).state,'expired');
    await page.route('**/api/shopping/approvals',route=>route.fulfill({status:403,contentType:'application/json',body:'{"error":"owner_required"}'}));
    await page.evaluate(()=>loadShoppingApprovals());
    assert.equal(await page.locator('.shopping-approval-card').count(),0);
    await context.close();
  }finally{await browser.close();await new Promise(resolve=>server.close(resolve))}
});
